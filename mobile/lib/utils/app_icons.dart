  static final Map<String, IconData> _mdiByCamelName = {
    for (final icon in MdiIcons.values)
      if (icon.mdiMetadata != null)
        icon.mdiMetadata!.name.split('-').asMap().entries.map((e) => e.key == 0 ? e.value : e.value[0].toUpperCase() + e.value.substring(1)).join(): icon,
  };

  static IconData? resolveBackendIcon(String camel) {
    return _lucideByMdiName[camel] ?? _mdiByCamelName[camel];
  }

  static IconData fromBackendString(String? raw, {IconData? fallback}) {
    final IconData fb = fallback ?? server;
    if (raw == null || raw.length < 4 || !raw.startsWith('mdi')) return fb;
    final String camel = raw.substring(3, 4).toLowerCase() + raw.substring(4);
    final IconData? lucide = _lucideByMdiName[camel];
    if (lucide != null) return lucide;
    return _mdiByCamelName[camel] ?? fb;
  }
